#!/usr/bin/env -S dotnet --

#region Purpose
// Pins the dev release attestation guard (kanban task 592): AttestationVerifyRunner against a
// throwaway git repo with a note signed by a throwaway key, and ReleaseAttestationGuard's
// pass / refuse / warn / off verdicts and walked-back-target remedy.
#endregion

#if !JARIBU_MULTI
return await RunAllTests();
#endif

namespace TimeWarp.Nuru.Tests.DevCli
{

using global::DevCli;

/// <summary>
/// End-to-end proof of the release-target attestation guard. Each test builds a scratch git
/// repository (global and system git config ignored, hooks off) and, where it needs a note,
/// signs it with a THROWAWAY Ed25519 key generated by <c>openssl genpkey</c> and injected via
/// the <c>keyOverride</c> seam. Nothing under <c>~/.timewarp/ganda/keys/</c> is touched.
/// </summary>
[TestTag("DevCli")]
public class ReleaseTargetAttestationTests
{
  [ModuleInitializer]
  internal static void Register() => RegisterTests<ReleaseTargetAttestationTests>();

  private const string ThrowawayKeyId = "tw-test-1";
  private const string FakeCheckSet = "deadbeefcafef00ddeadbeefcafef00ddeadbeefcafef00ddeadbeefcafef00d";
  private const string FakeTs = "2026-11-18T12:00:00Z";

  public static async Task Attested_target_passes_with_key_id()
  {
    using Fixture fixture = await Fixture.CreateAsync();
    string target = await fixture.CommitAsync("source/a.cs", "class A {}");
    string tree = await fixture.TreeOfAsync(target);
    await fixture.AttestAsync(tree);

    AttestationVerifyOutcome outcome = await AttestationVerifyRunner.VerifyAsync(fixture.Root, target, fixture.KeyOverride);
    outcome.Status.ShouldBe(AttestationVerificationStatus.Valid);
    outcome.Tree.ShouldBe(tree);
    outcome.KeyId.ShouldBe(ThrowawayKeyId);

    ReleaseAttestationGuardVerdict verdict = ReleaseAttestationGuard.Check(AttestationMode.Require, target, target, outcome);
    verdict.Kind.ShouldBe(ReleaseAttestationGuardKind.Pass);
    verdict.Lines.Count.ShouldBe(1);
    verdict.Lines[0].ShouldBe($"✓ target tree {tree[..12]} attested (key_id={ThrowawayKeyId})");
  }

  public static async Task Missing_note_refuses_under_require_with_head_remedy()
  {
    using Fixture fixture = await Fixture.CreateAsync();
    string target = await fixture.CommitAsync("source/a.cs", "class A {}");
    string tree = await fixture.TreeOfAsync(target);

    AttestationVerifyOutcome outcome = await AttestationVerifyRunner.VerifyAsync(fixture.Root, target, fixture.KeyOverride);
    outcome.Status.ShouldBe(AttestationVerificationStatus.NoNote);

    ReleaseAttestationGuardVerdict verdict = ReleaseAttestationGuard.Check(AttestationMode.Require, target, target, outcome);
    verdict.Kind.ShouldBe(ReleaseAttestationGuardKind.Refuse);

    string block = string.Join('\n', verdict.Lines);
    block.ShouldContain($"release target {target[..12]} is not attested (NoNote)");
    block.ShouldContain($"commit: {target}");
    block.ShouldContain($"tree:   {tree}");
    block.ShouldContain("status: NoNote");
    block.ShouldContain("HEAD is the target");
    block.ShouldContain("git pull --ff-only");
    block.ShouldContain("ganda repo attest");
    block.ShouldNotContain("git switch -c");
  }

  public static async Task Missing_note_warns_under_warn()
  {
    using Fixture fixture = await Fixture.CreateAsync();
    string target = await fixture.CommitAsync("source/a.cs", "class A {}");

    AttestationVerifyOutcome outcome = await AttestationVerifyRunner.VerifyAsync(fixture.Root, target, fixture.KeyOverride);

    ReleaseAttestationGuardVerdict verdict = ReleaseAttestationGuard.Check(AttestationMode.Warn, target, target, outcome);
    verdict.Kind.ShouldBe(ReleaseAttestationGuardKind.Warn);
    verdict.Lines[0].ShouldContain("attestation.mode=warn, continuing");
    string.Join('\n', verdict.Lines).ShouldContain("ganda repo attest");
  }

  public static async Task Off_mode_is_skipped_without_an_outcome()
  {
    ReleaseAttestationGuardVerdict verdict = ReleaseAttestationGuard.Check(AttestationMode.Off, "abc123", "abc123", outcome: null);
    verdict.Kind.ShouldBe(ReleaseAttestationGuardKind.Skipped);
    verdict.Lines.ShouldBe(["attestation skipped (attestation.mode=off)"]);

    await Task.CompletedTask;
  }

  public static async Task Head_note_does_not_satisfy_walked_back_target()
  {
    using Fixture fixture = await Fixture.CreateAsync();
    string target = await fixture.CommitAsync("source/a.cs", "class A {}");
    string head = await fixture.CommitAsync("kanban/done/001.md", "# board move");
    string headTree = await fixture.TreeOfAsync(head);
    string targetTree = await fixture.TreeOfAsync(target);
    targetTree.ShouldNotBe(headTree);
    await fixture.AttestAsync(headTree);

    AttestationVerifyOutcome headOutcome = await AttestationVerifyRunner.VerifyAsync(fixture.Root, head, fixture.KeyOverride);
    headOutcome.Status.ShouldBe(AttestationVerificationStatus.Valid);

    AttestationVerifyOutcome targetOutcome = await AttestationVerifyRunner.VerifyAsync(fixture.Root, target, fixture.KeyOverride);
    targetOutcome.Status.ShouldBe(AttestationVerificationStatus.NoNote);
    targetOutcome.Tree.ShouldBe(targetTree);

    ReleaseAttestationGuardVerdict verdict = ReleaseAttestationGuard.Check(AttestationMode.Require, target, head, targetOutcome);
    verdict.Kind.ShouldBe(ReleaseAttestationGuardKind.Refuse);

    string block = string.Join('\n', verdict.Lines);
    block.ShouldContain($"git switch -c attest-{target[..12]} {target}");
    block.ShouldContain("git branch --set-upstream-to=origin/master");
    block.ShouldContain("ganda repo attest");
    block.ShouldContain($"git branch -D attest-{target[..12]}");
    block.ShouldNotContain("HEAD is the target");
  }

  public static async Task Unknown_key_remedy_names_devcli_update()
  {
    AttestationVerifyOutcome outcome = new(AttestationVerificationStatus.UnknownKey, "1234567890abcdef", null, null, "key_id 'tw-audit-9' is not in the known-key registry", "tw-audit-9");

    ReleaseAttestationGuardVerdict verdict = ReleaseAttestationGuard.Check(AttestationMode.Require, "aaaa", "aaaa", outcome);
    verdict.Kind.ShouldBe(ReleaseAttestationGuardKind.Refuse);

    string block = string.Join('\n', verdict.Lines);
    block.ShouldContain("status: UnknownKey");
    block.ShouldContain("update TimeWarp.Nuru.DevCli");
    block.ShouldContain("tw-audit-9");
    block.ShouldNotContain("ganda repo attest");

    await Task.CompletedTask;
  }

  public static async Task Release_mode_resolution_matches_release_job()
  {
    ReleaseAttestationGuard.ResolveReleaseMode(null).ShouldBe((AttestationMode.Require, null));
    ReleaseAttestationGuard.ResolveReleaseMode("  ").ShouldBe((AttestationMode.Require, null));
    ReleaseAttestationGuard.ResolveReleaseMode("warn").ShouldBe((AttestationMode.Warn, null));
    ReleaseAttestationGuard.ResolveReleaseMode("OFF").ShouldBe((AttestationMode.Off, null));

    (AttestationMode mode, string? warning) = ReleaseAttestationGuard.ResolveReleaseMode("requiree");
    mode.ShouldBe(AttestationMode.Require);
    warning.ShouldNotBeNull();
    warning.ShouldContain("'requiree'");

    await Task.CompletedTask;
  }

  /// <summary>Scratch git repository plus a throwaway Ed25519 key.</summary>
  private sealed class Fixture : IDisposable
  {
    private readonly DirectoryInfo WorkDir;
    private readonly string PrivateKeyPath;

    private Fixture(DirectoryInfo workDir, string privateKeyPath, IReadOnlyDictionary<string, string> keyOverride)
    {
      WorkDir = workDir;
      PrivateKeyPath = privateKeyPath;
      KeyOverride = keyOverride;
    }

    public string Root => Path.Combine(WorkDir.FullName, "repo");

    public IReadOnlyDictionary<string, string> KeyOverride { get; }

    public static async Task<Fixture> CreateAsync()
    {
      DirectoryInfo workDir = Directory.CreateTempSubdirectory("release-attest-test-");
      string privPemPath = Path.Combine(workDir.FullName, "throwaway-priv.pem");
      string pubDerPath = Path.Combine(workDir.FullName, "throwaway-pub.der");

      await RunAsync(workDir.FullName, "openssl", "genpkey", "-algorithm", "ed25519", "-out", privPemPath);
      await RunAsync(workDir.FullName, "openssl", "pkey", "-in", privPemPath, "-pubout", "-outform", "DER", "-out", pubDerPath);

      byte[] pubDer = await File.ReadAllBytesAsync(pubDerPath);
      string publicKeyHex = Convert.ToHexString(pubDer[^32..]).ToLowerInvariant();
      Dictionary<string, string> keyOverride = new(StringComparer.Ordinal) { [ThrowawayKeyId] = publicKeyHex };

      Fixture fixture = new(workDir, privPemPath, keyOverride);
      Directory.CreateDirectory(fixture.Root);
      await fixture.GitAsync("init", "-q", "-b", "master");
      return fixture;
    }

    public async Task<string> CommitAsync(string relativePath, string content)
    {
      string path = Path.Combine(Root, relativePath);
      Directory.CreateDirectory(Path.GetDirectoryName(path)!);
      await File.WriteAllTextAsync(path, content);
      await GitAsync("add", "-A");
      await GitAsync("commit", "-q", "-m", $"add {relativePath}");
      return (await GitAsync("rev-parse", "HEAD")).Trim();
    }

    public async Task<string> TreeOfAsync(string commit) =>
      (await GitAsync("rev-parse", $"{commit}^{{tree}}")).Trim();

    public async Task AttestAsync(string tree)
    {
      byte[] canonical = AttestationVerifier.BuildCanonicalBytes(tree, FakeCheckSet, FakeTs, ThrowawayKeyId);
      string payloadPath = Path.Combine(WorkDir.FullName, $"payload-{tree}.bin");
      string sigPath = Path.Combine(WorkDir.FullName, $"sig-{tree}.bin");
      await File.WriteAllBytesAsync(payloadPath, canonical);
      await RunAsync(WorkDir.FullName, "openssl", "pkeyutl", "-sign", "-inkey", PrivateKeyPath, "-rawin", "-in", payloadPath, "-out", sigPath);

      byte[] sig = await File.ReadAllBytesAsync(sigPath);
      string sigBase64Url = Convert.ToBase64String(sig).TrimEnd('=').Replace('+', '-').Replace('/', '_');
      string noteJson =
        $$"""{"v":1,"alg":"ed25519","tree":"{{tree}}","check_set":"{{FakeCheckSet}}","ts":"{{FakeTs}}","key_id":"{{ThrowawayKeyId}}","sig":"{{sigBase64Url}}"}""";

      await GitAsync("notes", $"--ref={AttestationVerifier.NotesRefShort}", "add", "-f", "-m", noteJson, tree);
    }

    public void Dispose() => WorkDir.Delete(recursive: true);

    private Task<string> GitAsync(params string[] arguments) =>
      RunAsync(Root, "git", ["-c", "user.name=Test", "-c", "user.email=test@example.invalid", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null", .. arguments]);

    private static async Task<string> RunAsync(string workingDirectory, string executable, params string[] arguments)
    {
      CommandOutput result = await Shell.Builder(executable)
        .WithArguments(arguments)
        .WithWorkingDirectory(workingDirectory)
        .WithEnvironmentVariable("GIT_CONFIG_GLOBAL", "/dev/null")
        .WithEnvironmentVariable("GIT_CONFIG_NOSYSTEM", "1")
        .WithNoValidation()
        .CaptureAsync(CancellationToken.None);

      result.ExitCode.ShouldBe(0, $"{executable} {string.Join(' ', arguments)}: {result.Stderr}");
      return result.Stdout;
    }
  }
}

} // namespace TimeWarp.Nuru.Tests.DevCli
